"""Member B starts here: train, evaluate, and export the shared power model."""
import argparse
import json
from pathlib import Path

import numpy as np
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

from prepare_and_validate import DATASET, FAULTS, PANEL_W, collect_samples, features, find_dataset

def export_model(intercept, coefficients, nominal_power, metrics, sample_count, split_date):
    metadata = {
        "dataset_source": f"kaggle:{DATASET}",
        "model_type": "Ridge regression (irradiance, PV temperature, fault class)",
        "features": ["GTI/1000", "(TPV-25)/25"] + [f"Fault={fault:g}" for fault in FAULTS],
        "fault_classes": FAULTS,
        "panel_rating_w": PANEL_W,
        "dataset_reference_power_w": nominal_power,
        "sample_count": sample_count,
        "sampling_note": "Reservoir sampled by fault label (maximum 12,000 readings per class); holdout metrics use this class-stratified sample rather than the raw event prevalence.",
        "chronological_test_split": split_date,
        "metrics_panel_equivalent_w": metrics,
        "intercept": float(intercept),
        "coefficients": [float(value) for value in coefficients],
        "scope_note": "Dataset has no panel angle or measured soiling percentage. Fault class is categorical. Power is scaled to a 150 W demo module using normal-fault dataset readings.",
    }
    Path("ml/trained_model.json").write_text(json.dumps(metadata, indent=2) + "\n")

    js_coefficients = json.dumps([float(value) for value in coefficients])
    js_faults = json.dumps(FAULTS)
    js = f'''// Member D starts here: dashboard prediction uses these generated model coefficients.
// Generated by ml/train_and_evaluate.py. Do not edit coefficients by hand.
// Source: Kaggle {DATASET}; power is normalized to a 150 W demo module.
export const ML_MODEL_METRICS = {json.dumps(metrics, indent=2)};
export const FAULT_CLASSES = {js_faults};
export const PANEL_RATING_W = {PANEL_W};
const INTERCEPT = {float(intercept)};
const COEFFICIENTS = {js_coefficients};

export function faultClassForSoiling(percent) {{
  if (percent < 12) return 0.0;
  if (percent < 35) return 2.1;
  if (percent < 55) return 2.2;
  return 2.3;
}}

export function predictPowerML(irradiance, temperature, faultClass = 0) {{
  const x = [irradiance / 1000, (temperature - 25) / 25,
    ...FAULT_CLASSES.map((fault) => fault === faultClass ? 1 : 0)];
  let normalized = INTERCEPT;
  for (let i = 0; i < x.length; i++) normalized += COEFFICIENTS[i] * x[i];
  return Number((Math.max(0, Math.min(1.15, normalized)) * PANEL_RATING_W).toFixed(1));
}}
'''
    Path("dashboard/src/mlModel.js").write_text(js)

    c_faults = ", ".join(f"{fault:.1f}f" for fault in FAULTS)
    c_coefficients = ", ".join(f"{value:.10g}f" for value in coefficients)
    header = f'''// Member C starts here: ESP32 inference uses this generated model header.
// Generated by ml/train_and_evaluate.py. Do not edit coefficients by hand.
#ifndef ML_MODEL_H
#define ML_MODEL_H
#include <Arduino.h>
constexpr float ML_PANEL_RATING_W = {PANEL_W:.1f}f;
constexpr float ML_INTERCEPT = {float(intercept):.10g}f;
constexpr float ML_FAULT_CLASSES[] = {{{c_faults}}};
constexpr float ML_COEFFICIENTS[] = {{{c_coefficients}}};
inline float predictPowerML(float irradiance, float temperature, float faultClass) {{
  float x[10] = {{irradiance / 1000.0f, (temperature - 25.0f) / 25.0f,
    0, 0, 0, 0, 0, 0, 0, 0}};
  for (int i = 0; i < 8; ++i) x[i + 2] = (faultClass == ML_FAULT_CLASSES[i]) ? 1.0f : 0.0f;
  float normalized = ML_INTERCEPT;
  for (int i = 0; i < 10; ++i) normalized += ML_COEFFICIENTS[i] * x[i];
  normalized = fmaxf(0.0f, fminf(1.15f, normalized));
  return normalized * ML_PANEL_RATING_W;
}}
#endif
'''
    Path("include/ml_model.h").write_text(header)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", help="Directory containing the three Kaggle CSV files")
    args = parser.parse_args()
    data_dir = find_dataset(args.data_dir)
    rows = collect_samples(data_dir)

    normal_high = [power for _, sun, _, fault, power in rows if fault == 0 and sun >= 500]
    if len(normal_high) < 100:
        raise SystemExit("Not enough normal-fault daylight rows to calibrate the demo panel scale.")
    nominal_power = float(np.percentile(normal_high, 95))

    split = int(len(rows) * 0.8)
    train, test = rows[:split], rows[split:]
    X_train = np.asarray([features(sun, temp, fault) for _, sun, temp, fault, _ in train])
    y_train = np.asarray([power / nominal_power for _, _, _, _, power in train])
    X_test = np.asarray([features(sun, temp, fault) for _, sun, temp, fault, _ in test])
    y_test_w = np.asarray([power * PANEL_W / nominal_power for _, _, _, _, power in test])

    model = Ridge(alpha=0.2)
    model.fit(X_train, y_train)
    predicted_w = np.clip(model.predict(X_test), 0, 1.15) * PANEL_W
    metrics = {
        "r2": float(r2_score(y_test_w, predicted_w)),
        "mae_w": float(mean_absolute_error(y_test_w, predicted_w)),
        "rmse_w": float(np.sqrt(mean_squared_error(y_test_w, predicted_w))),
        "test_rows": len(test),
    }
    export_model(model.intercept_, model.coef_, nominal_power, metrics, len(rows), test[0][0])
    print(f"Matched rows: {len(rows):,}; chronological test rows: {len(test):,}")
    print(f"Equivalent panel scale: {nominal_power:.1f} W dataset reference -> {PANEL_W:.0f} W demo module")
    print(f"Holdout metrics (150 W equivalent): R²={metrics['r2']:.3f}, MAE={metrics['mae_w']:.2f} W, RMSE={metrics['rmse_w']:.2f} W")
    print("Updated ml/trained_model.json, dashboard/src/mlModel.js, and include/ml_model.h")


if __name__ == "__main__":
    main()
